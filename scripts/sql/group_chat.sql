CREATE TABLE IF NOT EXISTS im_groups (
 id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 name VARCHAR(256) NOT NULL, owner BIGINT UNSIGNED NOT NULL,
 member_count BIGINT UNSIGNED NOT NULL DEFAULT 1,
 dismissed TINYINT NOT NULL DEFAULT 0,
 last_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
 UNIQUE KEY owner_creation (owner,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS im_group_members (
 group_id BIGINT UNSIGNED NOT NULL, account BIGINT UNSIGNED NOT NULL,
 active TINYINT NOT NULL DEFAULT 1, epoch BIGINT UNSIGNED NOT NULL DEFAULT 1,
 join_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
 ack_seq BIGINT UNSIGNED NOT NULL DEFAULT 0, read_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
 PRIMARY KEY(group_id,account), KEY account_groups(account,group_id),
 FOREIGN KEY(group_id) REFERENCES im_groups(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS im_group_applications (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 group_id BIGINT UNSIGNED NOT NULL, account BIGINT UNSIGNED NOT NULL,
 reason VARCHAR(512) NOT NULL, status TINYINT NOT NULL DEFAULT 0,
 created_time BIGINT NOT NULL,
 KEY group_page(group_id,id), KEY applicant(account,id),
 FOREIGN KEY(group_id) REFERENCES im_groups(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS im_group_messages (
 group_id BIGINT UNSIGNED NOT NULL, seq BIGINT UNSIGNED NOT NULL,
 id VARCHAR(64) NOT NULL, client_id VARCHAR(64) NOT NULL,
 sender BIGINT UNSIGNED NOT NULL, nickname VARCHAR(256) NOT NULL,
 text MEDIUMTEXT NOT NULL, created_time BIGINT NOT NULL,
 PRIMARY KEY(group_id,seq), UNIQUE KEY message_id(id),
 UNIQUE KEY sender_request(group_id,sender,client_id),
 KEY sender_progress(group_id,sender,seq),
 FOREIGN KEY(group_id) REFERENCES im_groups(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS im_group_requests (
 actor BIGINT UNSIGNED NOT NULL, client_id VARCHAR(64) NOT NULL,
 payload MEDIUMTEXT NOT NULL, reply MEDIUMTEXT NOT NULL,
 PRIMARY KEY(actor,client_id)
) ENGINE=InnoDB DEFAULT CHARSET=ascii;

CREATE TABLE IF NOT EXISTS im_group_numbers (
 group_id BIGINT UNSIGNED PRIMARY KEY, number BIGINT UNSIGNED NOT NULL UNIQUE,
 FOREIGN KEY(group_id) REFERENCES im_groups(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS im_group_number_cursor (
 id TINYINT PRIMARY KEY, next_number BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB;
